// Builds single-file executables of `vibeshare` (every node type, GUI included)
// for Linux, macOS and Windows with Bun's cross-compiler. Run: npm run binaries
//   --targets linux-x64,darwin-arm64   only some targets
import { execFileSync } from 'node:child_process';
import { createHash } from 'node:crypto';
import { existsSync, mkdirSync, readdirSync, readFileSync, statSync, writeFileSync } from 'node:fs';
import { join, relative, resolve } from 'node:path';

const root = resolve(import.meta.dirname, '..');
const guiDist = join(root, 'gui', 'dist');
const embedded = join(root, 'src', 'shared', 'gui-embedded.ts');
const out = join(root, 'release');

const ALL = ['linux-x64', 'linux-arm64', 'darwin-x64', 'darwin-arm64', 'windows-x64'];
const flag = process.argv.indexOf('--targets');
const targets = flag > 0 ? process.argv[flag + 1].split(',') : ALL;
const version = JSON.parse(readFileSync(join(root, 'package.json'), 'utf8')).version as string;

function files(dir: string): string[] {
  return readdirSync(dir).flatMap((name) => {
    const path = join(dir, name);
    return statSync(path).isDirectory() ? files(path) : [path];
  });
}

if (!existsSync(join(guiDist, 'index.html'))) {
  console.log('Building the GUI…');
  execFileSync('npm', ['--prefix', 'gui', 'run', 'build'], { cwd: root, stdio: 'inherit', shell: process.platform === 'win32' });
}

const stub = readFileSync(embedded, 'utf8');
const bundle: Record<string, string> = {};
for (const file of files(guiDist)) bundle[relative(guiDist, file).split('\\').join('/')] = readFileSync(file).toString('base64');
writeFileSync(
  embedded,
  `// Generated by scripts/build-binaries.ts — do not commit.\nexport const EMBEDDED_GUI: Record<string, string> | null = ${JSON.stringify(bundle)};\n`
);

mkdirSync(out, { recursive: true });
const sums: string[] = [];
try {
  for (const target of targets) {
    if (!ALL.includes(target)) throw new Error(`Unknown target ${target} (${ALL.join(', ')})`);
    const name = `vibeshare-${version}-${target.replace('darwin', 'macos')}${target.startsWith('windows') ? '.exe' : ''}`;
    console.log(`Compiling ${name}…`);
    execFileSync(
      'bun',
      ['build', 'src/cli.ts', '--compile', '--minify', `--target=bun-${target}`, `--outfile=${join(out, name)}`],
      { cwd: root, stdio: 'inherit', shell: process.platform === 'win32' }
    );
    sums.push(`${createHash('sha256').update(readFileSync(join(out, name))).digest('hex')}  ${name}`);
  }
} finally {
  writeFileSync(embedded, stub);
}
writeFileSync(join(out, `SHA256SUMS-${version}.txt`), sums.join('\n') + '\n');
console.log(`\nDone: ${out}`);
